type ParentPortalLanguageContextValue = {
  language: ParentPortalLanguage;
  setLanguage: (language: ParentPortalLanguage) => void;
  t: (key: keyof typeof ui) => string;
  phrase: (value: string) => string;
};

const ParentPortalLanguageContext = createContext<ParentPortalLanguageContextValue | null>(null);

export const ParentPortalLanguageProvider = ({ children }: { children: React.ReactNode }) => {
  const [language, setLanguageState] = useState<ParentPortalLanguage>(() => {
    const saved = window.localStorage.getItem(STORAGE_KEY) as ParentPortalLanguage | null;
    return saved && parentPortalLanguages.some((item) => item.code === saved) ? saved : 'uz-lat';
  });

  const setLanguage = (nextLanguage: ParentPortalLanguage) => {
    setLanguageState(nextLanguage);
    window.localStorage.setItem(STORAGE_KEY, nextLanguage);
  };

  const value = useMemo<ParentPortalLanguageContextValue>(() => ({
    language,
    setLanguage,
    t: (key) => ui[key][language],
    phrase: (valueToTranslate) => {
      if (language === 'uz-lat') return valueToTranslate;

      const dictionary = phraseTranslations[language] || {};
      const trimmed = valueToTranslate.trim();
      if (dictionary[trimmed]) return dictionary[trimmed];

      const parentCompletion = trimmed.match(/^(\d+)\/4\s+ta\s+ma['ʼ]lumot\s+to['ʻ]ldirilgan$/i);
      if (parentCompletion) {
        const suffix: Record<Exclude<ParentPortalLanguage, 'uz-lat'>, string> = {
          'uz-cyr': 'ТА МАЪЛУМОТ ТЎЛДИРИЛГАН',
          en: 'FIELDS COMPLETED',
          ru: 'ПОЛЯ ЗАПОЛНЕНЫ',
        };
        return `${parentCompletion[1]}/4 ${suffix[language]}`;
      }

      const planTitle = trimmed.match(/^(.+)\s+tarifi$/i);
      if (planTitle && dictionary.tarifi) return `${planTitle[1]} ${dictionary.tarifi}`;

      const providerPayment = trimmed.match(/^(.+)\s+orqali to['ʻ]lov qilish$/i);
      if (providerPayment && dictionary["orqali to'lov qilish"]) {
        return language === 'en'
          ? `${dictionary["orqali to'lov qilish"]} ${providerPayment[1]}`
          : `${dictionary["orqali to'lov qilish"]} ${providerPayment[1]}`;
      }

      let translated = trimmed;
      Object.entries(dictionary)
        .filter(([source]) => source.length >= 5 && translated.includes(source))
        .sort(([a], [b]) => b.length - a.length)
        .forEach(([source, target]) => {
          translated = translated.split(source).join(target);
        });

      return translated;
    },
  }), [language]);

  return (
    <ParentPortalLanguageContext.Provider value={value}>
      {children}
    </ParentPortalLanguageContext.Provider>
  );
};

export const useParentPortalLanguage = () => {
  const context = useContext(ParentPortalLanguageContext);
  if (!context) {
    throw new Error('useParentPortalLanguage must be used inside ParentPortalLanguageProvider');
  }
  return context;
};

const originalTextNodes = new WeakMap<Text, string>();
const translatedAttributes = ['placeholder', 'title', 'aria-label'] as const;

const resolveOriginalPhrase = (value: string) => {
  const trimmed = value.trim();
  if (!trimmed) return value;

  for (const dictionary of Object.values(phraseTranslations)) {
    for (const [source, target] of Object.entries(dictionary)) {
      if (trimmed === target) return preserveOuterWhitespace(value, source);
    }
  }

  for (const translations of Object.values(ui)) {
    for (const [sourceLanguage, target] of Object.entries(translations)) {
      if (sourceLanguage !== 'uz-lat' && trimmed === target) return preserveOuterWhitespace(value, translations['uz-lat']);
    }
  }

  return value;
};

const preserveOuterWhitespace = (current: string, translated: string) => {
  const prefix = current.match(/^\s*/)?.[0] || '';
  const suffix = current.match(/\s*$/)?.[0] || '';
  return `${prefix}${translated}${suffix}`;
};

export const ParentPortalAutoTranslator = () => {
  const { language, phrase } = useParentPortalLanguage();

  useEffect(() => {
    const root = document.querySelector('.kg-parent-portal');
    if (!root) return;

    const translateRoot = () => {
      const walker = document.createTreeWalker(root, NodeFilter.SHOW_TEXT, {
        acceptNode: (node) => {
          const parent = node.parentElement;
          if (!parent || parent.closest('script,style,input,textarea,select,[data-kg-no-translate="true"]')) return NodeFilter.FILTER_REJECT;
          return node.textContent?.trim() ? NodeFilter.FILTER_ACCEPT : NodeFilter.FILTER_REJECT;
        },
      });

      let node = walker.nextNode() as Text | null;
      while (node) {
        const original = originalTextNodes.get(node) || resolveOriginalPhrase(node.textContent || '');
        if (!originalTextNodes.has(node)) originalTextNodes.set(node, original);
        const translated = phrase(original.trim());
        node.textContent = preserveOuterWhitespace(original, translated);
        node = walker.nextNode() as Text | null;
      }

      root.querySelectorAll<HTMLElement>('*').forEach((element) => {
        if (element.closest('[data-kg-no-translate="true"]')) return;
        translatedAttributes.forEach((attr) => {
          const current = element.getAttribute(attr);
          if (!current) return;
          const dataKey = `kgI18nOriginal${attr.replace(/-([a-z])/g, (_, letter) => letter.toUpperCase())}`;
          const original = element.dataset[dataKey] || resolveOriginalPhrase(current);
          element.dataset[dataKey] = original;
          element.setAttribute(attr, phrase(original));
        });
      });
    };

    translateRoot();
    const observer = new MutationObserver(() => window.requestAnimationFrame(translateRoot));
    observer.observe(root, { childList: true, subtree: true, characterData: true, attributes: true });
    return () => observer.disconnect();
  }, [language, phrase]);

  return null;
};

