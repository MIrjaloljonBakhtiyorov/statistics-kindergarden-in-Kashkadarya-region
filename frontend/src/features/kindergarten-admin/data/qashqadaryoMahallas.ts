const normalizeLookupText = (value?: string) => String(value || '')
  .trim()
  .toLowerCase()
  .replace(/[\u2018\u2019`]/g, "'")
  .replace(/\./g, '')
  .replace(/\s+/g, ' ');

const districtLookupMap = new Map(
  Object.keys(QASHQADARYO_MAHALLAS_BY_DISTRICT).map((district) => [
    normalizeLookupText(district),
    district,
  ])
);

export const getMahallasByDistrict = (district?: string) => {
  const key = districtLookupMap.get(normalizeLookupText(district));
  return key ? QASHQADARYO_MAHALLAS_BY_DISTRICT[key] : [];
};

export const getMahallaByName = (district?: string, mahalla?: string) =>
  getMahallasByDistrict(district).find((item) => normalizeLookupText(item.name) === normalizeLookupText(mahalla));
